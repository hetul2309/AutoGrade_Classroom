"""
backend/app/trustgrade/output_validator.py
-----------------------------------------
Strict output validation, mark clamping, and administrative state integrity verification.
Guarantees marks remain within [0.0, max_marks] and prevents prompt injection from tampering
with plagiarism flags.
"""

import math
import logging
from typing import Any

logger = logging.getLogger("trustgrade.output_validator")


def validate_and_clamp_grade(
    raw_marks: Any,
    max_marks: float,
    flagged: bool,
    flag_reason: str | None,
    had_similarity_flag: bool,
    detection_result: Any = None,
) -> tuple[float, bool, str | None, list[str]]:
    """
    Validates model outputs:
    1. Clamps marks strictly to [0.0, max_marks].
    2. Enforces non-NaN, non-Infinite numerical types.
    3. Prevents suppression of pre-computed similarity flags.
    4. Prevents fraudulent peer-flagging induced by student injection.

    Returns:
        (clamped_marks, validated_flagged, validated_flag_reason, audit_notices)
    """
    audit_notices = []

    # 1. Validate numerical marks
    try:
        val = float(raw_marks)
        if math.isnan(val) or math.isinf(val):
            val = 0.0
            audit_notices.append("Marks value was NaN/Inf; clamped to 0.0")
    except (ValueError, TypeError):
        val = 0.0
        audit_notices.append(f"Invalid non-numeric marks value '{raw_marks}'; coerced to 0.0")

    # Clamping
    if val > max_marks:
        audit_notices.append(f"Mark inflation blocked: {val} exceeded max_marks {max_marks}; clamped to {max_marks}")
        val = max_marks
    elif val < 0.0:
        audit_notices.append(f"Negative mark blocked: {val} clamped to 0.0")
        val = 0.0

    # 2. Administrative Flag Protection
    out_flagged = bool(flagged)
    out_flag_reason = flag_reason

    if had_similarity_flag:
        # Pre-computed copy case: cannot be suppressed by student prompt injection
        if not out_flagged:
            out_flagged = True
            audit_notices.append("Similarity flag suppression prevented: restored flagged=True from verified AST check")
    else:
        # No pre-computed copy case: verify that student injection did not invent a fraudulent peer flag
        if out_flagged and out_flag_reason:
            if "student " in out_flag_reason.lower() or "cheated" in out_flag_reason.lower():
                # Flag was not generated by our similarity engine; likely student injection
                out_flagged = False
                out_flag_reason = None
                audit_notices.append("Fraudulent peer-flagging attempt neutralized")

    # 3. Detection Notice Annotation
    if detection_result and getattr(detection_result, "is_suspicious", False):
        audit_notices.append(f"TrustGrade flagged submission for review ({detection_result.threat_level} risk)")

    return round(val, 2), out_flagged, out_flag_reason, audit_notices
